package com.pawtrail.pet.domain.enums;

/**
 * 반려동물의 종입니다.
 *
 * 사용자가 고르지 않고 breed.species 에서 그대로 옵니다.
 * 화면의 종 드롭다운이 곧 견종 목록이고 맨 끝 두 줄이 MIX 와 OTHER 이기 때문입니다.
 *
 * 종이 개가 아니어도 판정은 개 기준으로 그대로 수행합니다.
 * 판정을 아예 안 하면 "그 외" 를 고른 사용자가 등록만 되고 서비스를 못 쓰게 됩니다.
 * 대신 장소 상세 상단에만 안내 문구 한 줄을 띄우며, 그 판단은 프론트가 이 값으로 합니다.
 */
public enum Species {

    // 개
    DOG,

    // 고양이
    //
    // 실측에서 고양이를 명시한 동반 조건이 하나도 나오지 않아
    // 지금 이 값을 가지는 견종 행은 없음
    CAT,

    // 그 밖의 반려동물
    //
    // 견종 목록 맨 끝의 OTHER 가 이 값을 가짐
    ETC
}
