package com.pawtrail.pet.domain.provider;

import java.util.Optional;
import java.util.UUID;

/**
 * 객체 저장소와 이야기하는 약속입니다.
 *
 * 이 인터페이스에 S3 라는 단어가 나오지 않습니다.
 * 무엇을 할 수 있는지만 적고 어떻게 하는지는 infrastructure 가 정합니다.
 *
 * 키를 만드는 규칙도 여기 둡니다.
 * 발급할 때와 검증할 때가 같은 규칙을 써야 하는데,
 * 두 곳에 따로 적으면 한쪽만 고쳐질 자리가 됩니다.
 */
public interface StorageProvider {

    /**
     * 반려동물 사진이 놓일 자리를 새로 하나 만듭니다.
     *
     *   pets/{accountId}/{uuid}
     *
     * 파일 이름을 서버가 만듭니다.
     * 요청의 fileName 을 키에 쓰지 않는 이유는, 정규화를 한 번 빠뜨리면
     * 거기 섞인 `/` 나 `..` 이 남의 계정 자리를 가리키게 되기 때문입니다.
     * fileName 은 형식을 아는 데만 씁니다.
     *
     * user-service 처럼 계정당 고정 키를 쓸 수 없습니다.
     * 한 사람이 여러 마리를 기르므로 덮어쓰기가 성립하지 않습니다.
     *
     * 반려동물 식별자를 키에 넣지도 않습니다.
     * 사진을 먼저 올리고 그 주소를 등록 요청에 담는 흐름이라
     * 이 시점에는 반려동물이 아직 없습니다.
     *
     * 확장자를 붙이지 않습니다.
     * 브라우저는 Content-Type 헤더를 보고 그리며, 그 값은 서명에 넣어 S3 가 보관합니다.
     *
     * 계정 식별자를 경로에 남기는 것은 탈퇴 처리에서 접두사로 한 번에 지우기 위함입니다.
     */
    String newPhotoKey(UUID accountId);

    /**
     * 그 자리의 서명 없는 주소를 만듭니다.
     *
     * 두 자리에 씁니다.
     *   업로드 응답의 fileUrl — 프론트가 등록 요청에 담아 보낼 값
     *   등록 요청 검증 — 들고 온 값이 우리 버킷의 주소인지 봄
     *
     * 이 주소로는 파일이 안 열립니다. 버킷이 퍼블릭 액세스를 차단해 두었기 때문입니다.
     * 보는 것은 presignDownload 가 만든 서명된 주소로만 됩니다.
     */
    String publicUrl(String key);

    /**
     * 서명 없는 주소에서 키를 꺼냅니다.
     *
     * 등록 요청이 들고 온 photoUrl 을 저장하기 전에 씁니다.
     * 우리 버킷의 주소가 아니거나 그 계정의 자리가 아니면 비어 있는 값을 돌려줍니다.
     *
     * 이 검증이 없으면 아무 외부 주소나 프로필에 박히고,
     * 나중에 그 키로 객체를 지우는 코드가 생기면 남의 파일을 지우는 도구가 됩니다.
     */
    Optional<String> extractOwnedKey(String url, UUID accountId);

    /**
     * 브라우저가 그 자리에 파일을 올릴 수 있는 주소를 만듭니다.
     *
     * 이 서버는 파일을 받지 않습니다. 주소만 만들어 주고 브라우저가 S3 로 직접 PUT 합니다.
     * 그래서 서버가 파일 크기만큼의 메모리도 대역폭도 쓰지 않습니다.
     *
     * contentType 과 contentLength 를 서명에 넣습니다.
     * 그 값이 아닌 요청은 S3 가 거부하므로 클라이언트 검증에 기대지 않게 됩니다.
     * 상한 자체는 부르는 쪽이 봅니다. 서명은 "요청한 크기와 다른 것" 만 막습니다.
     */
    String presignUpload(String key, String contentType, long contentLength);

    /**
     * 그 자리의 파일을 볼 수 있는 주소를 만듭니다.
     *
     * 버킷이 퍼블릭 액세스를 차단해 두었으므로 서명 없이는 열리지 않습니다.
     * 조회 응답의 photoUrl 이 매번 이 값으로 나갑니다.
     *
     * 그래서 그 응답은 캐시하면 안 됩니다. 서명이 만료되면 깨진 이미지가 됩니다.
     */
    String presignDownload(String key);

    /**
     * 그 자리의 파일을 지웁니다.
     *
     * 없는 키를 지워도 S3 는 오류를 내지 않습니다.
     * 사진을 안 올린 반려동물을 지워도 그대로 지나갑니다.
     */
    void delete(String key);
}
